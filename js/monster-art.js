/* Quadro e escala comuns para que as criaturas tenham o tamanho do personagem. */
function creatureSprite(id,w,h,draw){
 const art=paint(w,h,draw),c=mkCanvas(40,24),x=c.getContext('2d');
 const scale=Math.min(18/w,16/h),dw=Math.max(1,Math.round(w*scale)),dh=Math.max(1,Math.round(h*scale));
 x.imageSmoothingEnabled=false;
 x.drawImage(art,Math.round((40-dw)/2),2,dw,dh);
 c.pad=11;c.anchorY=6;
 const sp={d:c,u:c,s:c,ds:c,us:c,w:null};
 SP[id]=sp;
}

